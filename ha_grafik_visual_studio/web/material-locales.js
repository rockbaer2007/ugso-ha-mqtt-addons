export const materialVocabulary = new Map(rows.trim().split('\n').map(line=>{const [de,en,fr]=line.split('|');return [de,{en,fr}];}));
const repeated={ 'Menüpunkt':['Menu item','Entrée'], 'Zeile':['Row','Ligne'], 'Datenreihe':['Series','Série'], 'Ansicht':['View','Vue'], 'Ziel':['Target','Cible'], 'Spalte':['Column','Colonne'], 'Zeilenzusätze':['Row extras','Options de ligne'], 'Datenreihenoptionen':['Series options','Options de série'], 'Ansichtsoptionen':['View options','Options de vue'] };
export function materialText(value,locale='de') {
  if(typeof value!=='string' || locale.startsWith('de'))return value;
  const language=locale.startsWith('fr')?'fr':'en',direct=materialVocabulary.get(value);if(direct)return direct[language];
  const indexed=value.match(/^(.*) \[(\d+)\]$/);if(indexed && repeated[indexed[1]])return `${repeated[indexed[1]][language==='fr'?1:0]} [${indexed[2]}]`;
  if(value.endsWith(' (erweitert)'))return `${materialText(value.slice(0,-12),locale)} (${language==='fr'?'avancé':'advanced'})`;
  for(const prefix of ['Farbe ','Größe '])if(value.startsWith(prefix))return `${language==='fr'?prefix==='Farbe '?'Couleur':'Taille':prefix==='Farbe '?'Color':'Size'}: ${materialText(value.slice(prefix.length),locale)}`;
  for(const prefix of ['Text ','Wert ','Zweiter Text '])if(value.startsWith(prefix))return `${materialText(prefix.trim(),locale)}: ${materialText(value.slice(prefix.length),locale)}`;
  return value;
}
