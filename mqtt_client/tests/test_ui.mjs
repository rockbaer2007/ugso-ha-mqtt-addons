import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
  const page=await browser.newPage({viewport:{width:1300,height:1000}}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.MQTT_UI_URL||'http://127.0.0.1:4186/');
  await page.waitForFunction(()=>document.querySelector('#broker_host').value==='demo-broker');
  assert.match(await page.locator('#statusDetails').innerText(),/HA: erreichbar.*Live-Ereignisse/);
  assert.match(await page.locator('#statusDetails').innerText(),/Wartend:.*Zusammengefasst:.*HA-Eingang:/);
  assert.equal(await page.locator('#credentialsToggle').getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('#broker_host').isVisible(),false);
  await page.locator('#credentialsToggle').click();
  assert.equal(await page.locator('#broker_host').isVisible(),true);
  await page.locator('#credentialsToggle').click();
  assert.equal(await page.locator('#broker_host').isVisible(),false);
  assert.equal(await page.locator('#save').isVisible(),true);
  await page.locator('#credentialsToggle').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#broker_host').isVisible(),true);
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#broker_host').value==='demo-broker');
  assert.equal(await page.locator('#broker_host').isVisible(),false);
  await page.locator('#credentialsToggle').click();
  await page.locator('#broker_host').fill('');
  await page.locator('#credentialsToggle').click();
  await page.locator('#save').click();
  assert.equal(await page.locator('#broker_host').isVisible(),true,'invalid required input opens credentials');
  await page.locator('#broker_host').fill('demo-broker');
  await page.locator('#credentialsToggle').click();
  assert.equal(await page.locator('#save').isVisible(),true);
  const scriptDownload=await page.request.get(new URL('downloads/ugso-mqtt-role-mapper.js',page.url()).href);
  assert.equal(scriptDownload.status(),200);
  assert.match(scriptDownload.headers()['content-disposition'],/attachment/);
  assert.match(await scriptDownload.text(),/mode: 'preview'/);
  assert.equal(await page.locator('#transferSettings').isVisible(),true);
  assert.equal(await page.locator('#publish_delay_ms').isVisible(),true);
  assert.equal(await page.locator('#tlsToggle').getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('[name=tls_ca]').isVisible(),false);
  assert.match(await page.locator('#tlsToggle').innerText(),/TLS nicht ausgewählt/);
  await page.locator('#tlsToggle').click();
  assert.equal(await page.locator('[name=tls_ca]').isVisible(),true);
  await page.locator('#tlsToggle').focus(); await page.keyboard.press('Enter');
  assert.equal(await page.locator('[name=tls_ca]').isVisible(),false);
  await page.route('**/api/label-diagnostics',route=>route.fulfill({json:{enabled:true,roots:[
    {entity_id:'switch.no_device',device_linked:false,candidates:[]},
    {entity_id:'switch.plug',device_linked:true,candidates:[{entity_id:'sensor.<script>literal</script>',device_class:'power',unit:'W',reason:'included',class_source:'unit'}]}
  ]}}));
  await page.locator('#readingDiagnostics').click();
  await page.waitForFunction(()=>document.querySelector('#readingReport').textContent.includes('aus Einheit'));
  assert.match(await page.locator('#readingReport').innerText(),/Keine HA-Gerätezuordnung/);
  assert.equal(await page.locator('#readingReport script').count(),0);
  await page.locator('#closeReadingDialog').click();
  await page.unroute('**/api/label-diagnostics');
  await page.locator('#transmissions').click();
  await page.waitForFunction(()=>document.querySelector('#transferList .transferRow'));
  assert.match(await page.locator('#transferList').innerText(),/Demo switch.*Manuell/s);
  assert.match(await page.locator('#transferList').innerText(),/Vom Broker bestätigt/);
  const snapshot=await(await page.request.get(new URL('api/transmissions',page.url()).href)).json();
  assert.equal(snapshot.values.some(row=>row.entity_id==='switch.test'&&row.origin==='manual'),true);
  assert.equal(JSON.stringify(snapshot).includes('test-private-password'),false);
  const sample=snapshot.values[0];
  await page.route('**/api/transmissions',route=>route.fulfill({json:{values:['manual','label','both'].map((origin,index)=>({...sample,origin,entity_id:'sensor.demo_'+index,name:index===2?'<script>Literal name</script>':'Demo '+index}))}}));
  await page.locator('#refreshTransfers').click();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('#transferList .origin'),node=>node.textContent).join('|')==='Manuell|Label|Beides');
  assert.deepEqual(await page.locator('#transferList .origin').allTextContents(),['Manuell','Label','Beides']);
  assert.equal(await page.locator('#transferList script').count(),0);
  assert.equal(new Set(await page.locator('#transferList .origin').evaluateAll(nodes=>nodes.map(node=>getComputedStyle(node).backgroundColor))).size,3);
  await page.locator('#transferSearch').fill('nothing-matches');
  assert.match(await page.locator('#transferList').innerText(),/Keine passenden/);
  await page.locator('#closeTransfers').click();
  await page.unroute('**/api/transmissions');
  await page.locator('#credentialsToggle').click();
  await page.locator('[name=poll_interval]').fill('17');
  await page.locator('#publish_delay_ms').fill('0');
  await page.locator('[name=label_device_readings]').check();
  await page.locator('#save').click(); await page.waitForFunction(()=>document.querySelector('#message').textContent.startsWith('Gespeichert'));
  const config=await(await page.request.get(new URL('api/config',page.url()).href)).json();
  assert.equal(config.poll_interval,17); assert.equal(config.publish_delay_ms,0); assert.equal(config.has_password,true);
  assert.equal(config.label_device_readings,true);
  assert.equal(config.tls,false);
  assert.equal(await page.locator('[name=tls_ca]').isVisible(),false);
  assert.equal(await page.locator('#broker_host').isVisible(),false);
  assert.equal(config.password,undefined); assert.equal(config.tls_key,undefined);
  const downloadEvent=page.waitForEvent('download'); await page.locator('#backup').click();
  const download=await downloadEvent, backup=JSON.parse(await readFile(await download.path(),'utf8'));
  assert.equal(backup.options.poll_interval,17); assert.equal(backup.options.password,undefined);
  assert.equal(backup.options.label_device_readings,true);
  assert.equal(backup.options.tls_key,undefined); assert.deepEqual(backup.options.entities,['switch.test']);
  page.once('dialog',dialog=>dialog.dismiss());
  await page.locator('#restoreFile').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  assert.equal((await(await page.request.get(new URL('api/config',page.url()).href)).json()).poll_interval,17);
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#restoreFile').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await page.waitForFunction(()=>document.querySelector('#message').textContent.startsWith('Sicherung geladen'));
  await page.locator('#retained').click(); await page.locator('#retainedDialog').waitFor();
  assert.match(await page.locator('#retainedList').innerText(),/ha_external\/old\/state/);
  await page.locator('#retainedList input').check(); page.once('dialog',dialog=>dialog.dismiss());
  await page.locator('#deleteRetained').click(); assert.equal(await page.locator('#retainedList input').count(),1);
  page.once('dialog',dialog=>dialog.accept()); await page.locator('#deleteRetained').click();
  await page.waitForFunction(()=>document.querySelector('#retainedList').textContent.includes('Keine erfassten'));
  assert.match(await page.locator('#message').innerText(),/1 Retain-Topics gelöscht/);
  await page.locator('#closeRetained').click();
  const rejected=await page.request.post(new URL('api/retained',page.url()).href,{data:{confirm:true,topics:['foreign/topic']}});
  assert.equal(rejected.status(),400);
  await page.locator('#credentialsToggle').click();
  await page.locator('#tlsToggle').click();
  const upload=page.locator('[data-pem=tls_ca]'); await upload.setInputFiles({name:'ca.pem',mimeType:'text/plain',buffer:Buffer.from('invalid-ca')});
  await page.waitForFunction(()=>document.querySelector('[name=tls_ca]').value==='invalid-ca');
  assert.equal(await page.locator('[name=tls_ca]').inputValue(),'invalid-ca');
  await page.locator('[name=tls]').check(); await page.locator('#save').click();
  assert.match(await page.locator('#tlsToggle').innerText(),/TLS ausgewählt/);
  await page.waitForFunction(()=>document.querySelector('#message').textContent==='SSLError');
  assert.equal((await(await page.request.get(new URL('api/config',page.url()).href)).json()).tls,false);
  await page.setViewportSize({width:390,height:900});
  const buttons=await page.locator('.connectionActions button').evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return {width:r.width,height:r.height,y:r.y};}));
  assert.equal(buttons[0].height,buttons[1].height); assert.equal(buttons[0].width,buttons[1].width); assert.equal(buttons[0].y,buttons[1].y);
  assert.equal(await page.locator('#save').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'compact mobile layout');
  assert.deepEqual(errors,[]);
  console.log('MQTT UI: detailed status, preserved settings/password, backup/restore, confirmed retain deletion, PEM validation and mobile layout passed.');
} finally {await browser.close();}
